"""Native vocabulary and contextual lexical rules shared by site and TextMate.

Coloring identifies source roles; it is not semantic validation or name resolution.
"""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
VOCABULARY_PATH = ROOT / 'crates/gwt-core/src/vocabulary.json'
VOCABULARY = json.loads(VOCABULARY_PATH.read_text())
IDENTIFIER = r'[A-Za-z_][A-Za-z0-9_]*'


def alternatives(words):
    return '|'.join(re.escape(word) for word in sorted(words, key=lambda w: (-len(w), w)))


def rules():
    v = VOCABULARY
    heads = [word for group in v['structural'].values() for word in group]
    # Ordered precedence applies at equal offsets. Capture-only matches preserve
    # unclassified names, whitespace and punctuation rather than guessing by case.
    return [
        (r'#[^\n]*', {0: 'comment'}),
        (r'"(?:\\.|[^"\\])*"', {0: 'string'}),
        (rf'^(\s*)(RECORD|TYPE)(\s+)({IDENTIFIER})\b', {2: 'kw', 4: 'type'}),
        (rf'^(\s*)({IDENTIFIER})(\s*:)', {2: 'key'}),
        (r'^(\s*)(DEPENDING)(\s+)(ON)\b', {2: 'kw', 4: 'kw'}),
        (rf'^(\s*)(?:(WHEN|AND)(\s+))?({alternatives(v["actions"])})\b', {2: 'kw', 4: 'action'}),
        (rf'^(\s*)(?:(WHEN|AND)(\s+))?({alternatives(heads)})\b', {2: 'kw', 4: 'kw'}),
        # Consume dotted paths before their components can be mistaken for words.
        (rf'\b{IDENTIFIER}(?:\.{IDENTIFIER})+\b', {}),
        (rf'(?<![A-Za-z0-9_])<({IDENTIFIER})>', {0: 'param'}),
        (r'\b\d+(?:\.\d+)?\b', {0: 'number'}),
        (rf'\b(?:{alternatives(v["literals"])})\b', {0: 'bool'}),
        (rf'\b(?:{alternatives(v["primitiveTypes"] + v["containers"])})\b', {0: 'type'}),
        (rf'\b(?:{alternatives(v["roundingModes"])})\b', {0: 'bool'}),
        (rf'\b(?:{alternatives(v["expressionWords"])})\b', {0: 'operator'}),
        (rf'\b(?:{alternatives(v["connectors"])})\b', {0: 'word'}),
        (r'==|!=|>=|<=|>|<|\+|-|\*|/|\|', {0: 'operator'}),
    ]


FILTER_RULE = (rf'\b(?:{alternatives(VOCABULARY["filter"]["accepted"])})\b', {0: 'kw'})
COLLECTION_HEADER = re.compile(r'^\s*(?:AND\s+)?(?:FOR|FIND)\b')


def tokens(source):
    """Yield source offsets and roles, leaving names in their original spelling."""
    compiled = [(re.compile(pattern), captures) for pattern, captures in rules()]
    offset = 0
    for line in source.splitlines(keepends=True):
        active = compiled[:]
        if COLLECTION_HEADER.match(line):
            active.insert(-1, (re.compile(FILTER_RULE[0]), FILTER_RULE[1]))
        cursor = 0
        while cursor < len(line):
            candidates = [(match.start(), rank, match, captures)
                          for rank, (pattern, captures) in enumerate(active)
                          if (match := pattern.search(line, cursor)) is not None]
            if not candidates:
                break
            _, _, match, captures = min(candidates, key=lambda row: row[:2])
            for group, role in captures.items():
                start, end = match.span(group)
                if start >= 0:
                    yield offset + start, offset + end, role
            cursor = match.end()
        offset += len(line)


def textmate():
    scopes = {'comment': 'comment.line.number-sign', 'string': 'string.quoted.double',
              'kw': 'keyword.control', 'type': 'storage.type', 'key': 'variable.other.property',
              'action': 'support.function.builtin', 'param': 'variable.parameter',
              'number': 'constant.numeric', 'bool': 'constant.language',
              'operator': 'keyword.operator', 'word': 'keyword.other.connector'}
    def pattern(rule):
        regex, captures = rule
        return {'match': regex, 'captures': {str(group): {'name': scopes[role] + '.gwt'} for group, role in captures.items()}}
    base = [pattern(rule) for rule in rules()]
    # A line context permits WHERE only in collection headers. Includes have
    # no recursive collection rule, so the header's own keyword still tokenizes.
    collection = {'begin': r'^(?=\s*(?:AND\s+)?(?:FOR|FIND)\b)', 'end': r'$',
                  'patterns': [pattern(FILTER_RULE), *base]}
    return {'name': 'GWT', 'scopeName': 'source.gwt',
            'comment': 'Generated by python tools/gwt_syntax.py; edit vocabulary.json and shared rules.',
            'patterns': [collection, *base]}


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'vscode-gwt/syntaxes/gwt.tmLanguage.json'
    expected = json.dumps(textmate(), indent=2) + '\n'
    if args.check:
        if path.read_text() != expected:
            raise SystemExit('TextMate grammar is stale: run python tools/gwt_syntax.py')
    else:
        path.write_text(expected)
