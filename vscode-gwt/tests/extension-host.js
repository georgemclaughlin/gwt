async function replace(document, text) {
  const edit = new vscode.WorkspaceEdit();
  edit.replace(document.uri, new vscode.Range(document.positionAt(0), document.positionAt(document.getText().length)), text);
  assert.equal(await vscode.workspace.applyEdit(edit), true);
}
async function check() { return vscode.commands.executeCommand('gwt.checkCurrentFile'); }
async function stableDefinition(document, position) {
  const version = document.version;
  const deadline = Date.now() + 5000;
  for (;;) {
    assert.equal(document.version, version, 'Source changed while awaiting a definition');
    const definitions = await vscode.commands.executeCommand('vscode.executeDefinitionProvider', document.uri, position);
    if (definitions?.length) return definitions;
    assert(Date.now() < deadline, 'Expected definition never became available');
    // A late filesystem notification can legitimately cancel one provider call.
    await new Promise(resolve => setTimeout(resolve, 50));
  }
}

